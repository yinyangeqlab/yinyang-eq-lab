import assert from 'node:assert/strict';
import {rankPreferences} from '../lib/preference-ranking.ts';
const targets=['a','b','c'].map(id=>({id,name:id,creator:'Test'}));
const vote=(id,voterId='one',winnerId='a',loserId='b',extra={})=>({id:String(id),voterId,winnerId,loserId,...extra});
const get=(r,id='a')=>r.rows.find(t=>t.id===id);
const one=rankPreferences(targets,[vote(0)]);
const repeated=rankPreferences(targets,Array.from({length:1000},(_,i)=>vote(i)));
assert.equal(repeated.voteCount,1000);
assert.equal(repeated.participantGroups,1);
assert.ok(Math.abs(get(one).rating-get(repeated).rating)<1e-7);
assert.ok(Math.abs(get(one).sd-get(repeated).sd)<1e-7,'Repeating the same answer cannot manufacture model certainty');
const reversed=rankPreferences(targets,[vote(0),vote(1,'one','b','a')]);
assert.ok(Math.abs(get(reversed).rating-1500)<1e-7);
const withTie=rankPreferences(targets,[vote(0),vote(1,'one','a','b',{result:'tie'})]);
assert.equal(get(withTie).ties,1);assert.equal(get(withTie).comparisons,2);
assert.ok(get(withTie).rating>1500&&get(withTie).rating<get(one).rating,'A tie actually moderates the preference');
const duplicate=rankPreferences(targets,[vote(0),vote(0)]);
assert.deepEqual(duplicate,one);
assert.deepEqual(rankPreferences(targets,[vote(0),vote(1,'one','a','a')]),one,'Identical-target diagnostics add no preference evidence');
const across=rankPreferences(targets,[vote(0),vote(1,'one','a','c'),vote(2,'one','b','c')]);
assert.ok(Math.abs(across.rows.reduce((n,r)=>n+r.effectiveComparisons,0)/2-1)<1e-8,'One participant has bounded total weight across ALL pairs');
const independent=rankPreferences(targets,Array.from({length:100},(_,i)=>vote(i,'account:'+i)));
assert.ok(get(independent).sd<get(one).sd);
assert.ok(get(independent).rating>get(one).rating);
assert.deepEqual(rankPreferences(targets,[vote(0,'one','a','b',{reliabilityWeight:.001})]),rankPreferences(targets,[vote(0,'one','a','b',{reliabilityWeight:1})]),'Diagnostic checks do not weight preferences');
// Balanced two-target cohorts recover a moderate preference instead of converting repeats to people.
const sixty=rankPreferences(targets,Array.from({length:100},(_,i)=>vote(i,'person:'+i,i<60?'a':'b',i<60?'b':'a')));
const difference=get(sixty,'a').rating-get(sixty,'b').rating;
const probability=1/(1+10**(-difference/400));assert.ok(probability>.57&&probability<.61);
const tiesOnly=rankPreferences(targets,Array.from({length:20},(_,i)=>vote(i,'person:'+i,'a','b',{result:'tie'})));
assert.equal(get(tiesOnly).rating,1500);assert.equal(get(tiesOnly).ties,20);
for(const r of [one,repeated,reversed,withTie,across,independent,sixty,tiesOnly])for(const row of r.rows){for(const key of ['rating','sd','lower','upper'])assert.ok(Number.isFinite(row[key]));assert.ok(row.sd>0&&row.sd<=350.00001);}
const ordered=rankPreferences(targets,[vote(0),vote(1,'two','a','c'),vote(2,'three','b','c')]);
const reorder=rankPreferences(targets,[vote(2,'three','b','c'),vote(0),vote(1,'two','a','c')]);
for(const row of ordered.rows)assert.ok(Math.abs(row.rating-get(reorder,row.id).rating)<1e-6);
console.log('Ranking checks passed: genuine repeats/reversals, ties, participant-wide influence bound, independent groups, duplicate rejection, check-weight independence, moderate known preference, finite sparse estimates, and order invariance. These are model checks, not population-coverage validation.');
