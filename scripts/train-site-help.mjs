import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { runInNewContext } from "node:vm";
import ts from "typescript";

const source = path => new URL("../" + path, import.meta.url);
function load(name, dependencies = {}) {
  const { outputText } = ts.transpileModule(readFileSync(source(`lib/${name}.ts`), "utf8"), {
    compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS },
  });
  const exports = {};
  runInNewContext(outputText, { exports, TextDecoder, require: key => {
    assert.ok(Object.hasOwn(dependencies, key), key);
    return dependencies[key];
  } });
  return exports;
}

const guide = load("site-help-guide");
const { createSiteHelpEncoder, SITE_HELP_MODEL_PATH } = load("site-help-model", {
  "./site-help-guide": guide, "./site-help-weights": {},
});
const bytes = readFileSync(source("public" + SITE_HELP_MODEL_PATH));
const encode = createSiteHelpEncoder(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength));
const prompts = JSON.parse(readFileSync(new URL("site-help-training.json", import.meta.url), "utf8"));
const labels = Object.keys(prompts).sort();
const vectors = [];
for (const [index, id] of labels.entries()) {
  const topic = guide.helpTopics.find(topic => topic.id === id);
  assert.ok(!id || topic, `Unknown approved topic ${id}`);
  const phrases = topic ? [topic.title, ...topic.terms.split(";")] : [];
  for (const phrase of [...new Set([...prompts[id], ...phrases].map(s => s.trim()))]) {
    const input = Float64Array.from([...encode(phrase), 1]);
    vectors.push({ input, index });
  }
}
const width = vectors[0].input.length;
const weights = labels.map(() => new Float64Array(width));
const logits = new Float64Array(labels.length);
for (let epoch = 0; epoch < 200; epoch++) {
  const gradient = labels.map(() => new Float64Array(width));
  for (const { input, index } of vectors) {
    for (let c = 0; c < labels.length; c++) {
      const row = weights[c];
      logits[c] = row.reduce((dot, weight, i) => dot + weight * input[i], 0);
    }
    const max = Math.max(...logits);
    const probabilities = logits.map(value => Math.exp(value - max));
    const total = probabilities.reduce((sum, value) => sum + value, 0);
    for (let c = 0; c < labels.length; c++) {
      const error = probabilities[c] / total - Number(c === index);
      for (let i = 0; i < width; i++) gradient[c][i] += error * input[i];
    }
  }
  for (let c = 0; c < labels.length; c++) {
    for (let i = 0; i < width; i++)
      weights[c][i] -= 8 * (gradient[c][i] / vectors.length + 0.0005 * weights[c][i]);
  }
}
// A fixed scale keeps the reviewed model compact and makes inference self-contained.
const rows = labels.map((id, index) => {
  const row = Buffer.alloc(width);
  for (const [i, value] of weights[index].entries()) row.writeInt8(Math.round(value * 16), i);
  return [id, row.toString("base64")];
});
const output = "// Generated by node scripts/train-site-help.mjs from reviewed synthetic questions.\n" +
  "export const siteHelpWeights = [\n" + rows.map(row => "  " + JSON.stringify(row) + ",\n").join("") + "] as const;\n";
writeFileSync(source("lib/site-help-weights.ts"), output);
console.log(`Trained ${labels.length - 1} guide topics and an out-of-scope class on ${vectors.length} examples. ${Buffer.byteLength(output)} bytes of source weights.`);
